for ws in wb.worksheets:
    headers = {c.value:c.column for c in ws[1]}
    if "사례 ID" not in headers: continue
    for row in range(2, ws.max_row + 1):
        case_id = ws.cell(row, headers["사례 ID"]).value
        if not case_id: continue
